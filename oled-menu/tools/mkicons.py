def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def grid(art):
    rows = [r for r in art.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    return [r.ljust(w, '.') for r in rows], w, len(rows)


def emit(out, png=None):
    lines = ['/* Сгенерировано tools/mkicons.py, руками не править. Свои значки в стиле oled_icons.h',
             ' * форка saqie1393: цветные 16x16 RGB565 (0 - прозрачно) и маски 4 бита для строки состояния. */',
             '#ifndef OLED_ICONS_EXT_H', '#define OLED_ICONS_EXT_H', '#include <stdint.h>', '',
             'struct mono_icon { uint8_t w, h; const uint8_t *a; };  /* a: по байту 0..15 на пиксель */', '']
    prev = []
    for name, art in COLOR.items():
        rows, w, h = grid(art)
        assert (w, h) == (16, 16), (name, w, h)
        vals = []
        for r in rows:
            for ch in r:
                c = PAL[ch]
                v = rgb565(c) if c else 0
                vals.append(v if (v or not c) else 1)
        lines.append('static const uint16_t %s[256] = {' % name)
        for i in range(0, 256, 16):
            lines.append('    ' + ','.join('0x%04X' % v for v in vals[i:i + 16]) + ',')
        lines.append('};')
        prev.append((name, rows, None))
    lines.append('')
    for name, art in MONO.items():
        rows, w, h = grid(art)
        a = [{'#': 15, '+': 9, '-': 5}.get(ch, 0) for r in rows for ch in r]
        lines.append('static const uint8_t %s_a[%d] = {%s};' % (name, len(a), ','.join(str(v) for v in a)))
        lines.append('static const struct mono_icon %s = {%d, %d, %s_a};' % (name, w, h, name))
        prev.append((name, rows, 'mono'))
    lines.append('\n#endif')
    open(out, 'w').write('\n'.join(lines) + '\n')
    if png:
        S = 6
        im = Image.new('RGB', (len(prev) * 18 * S, 18 * S), (40, 40, 40))
        for k, (name, rows, kind) in enumerate(prev):
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    if kind:
                        v = {'#': 255, '+': 150, '-': 85}.get(ch)
                        c = (v, v, v) if v else None
                    else:
                        c = PAL[ch]
                    if c:
                        for dy in range(S):
                            for dx in range(S):
                                im.putpixel(((k * 18 + 1 + x) * S + dx, (1 + y) * S + dy), c)
        im.save(png)


if __name__ == '__main__':
    emit(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
